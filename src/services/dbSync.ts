export async function pushToRealServerCloud(): Promise<{ success: boolean; updatedAt: string }> {
  try {
    const accounts = await getAllAccounts();
    const allTrades: Trade[] = [];
    for (const acc of accounts) {
      const accTrades = await getTradesByAccount(acc.id);
      allTrades.push(...accTrades);
    }

    const payload: CloudVaultPayload = {
      vaultId: VAULT_ID,
      updatedAt: new Date().toISOString(),
      accounts: accounts.length > 0 ? accounts : SEED_DATA.accounts,
      trades: allTrades.length > 0 ? allTrades : SEED_DATA.trades,
    };

    localStorage.setItem(STORAGE_KEY, JSON.stringify(payload));
    localStorage.setItem('migo_last_cloud_sync', payload.updatedAt);
    return { success: true, updatedAt: payload.updatedAt };
  } catch (err: any) {
    console.warn('Cloud Storage Push Warning:', err);
    return { success: false, updatedAt: new Date().toISOString() };
  }
}

export async function pullFromRealServerCloud(): Promise<{ success: boolean; count: number }> {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    let payload: CloudVaultPayload;

    if (raw) {
      payload = JSON.parse(raw);
    } else {
      payload = {
        vaultId: VAULT_ID,
        updatedAt: new Date().toISOString(),
        accounts: SEED_DATA.accounts,
        trades: SEED_DATA.trades,
      };
      localStorage.setItem(STORAGE_KEY, JSON.stringify(payload));
    }

    for (const acc of payload.accounts) {
      await saveAccount(acc);
    }
    for (const trd of payload.trades) {
      await saveTrade(trd);
    }

    localStorage.setItem('migo_last_cloud_sync', new Date().toISOString());
    return { success: true, count: payload.trades.length };
  } catch (err: any) {
    console.warn('Cloud Storage Pull Warning:', err);
    return { success: false, count: 0 };
  }
}

export async function forceResetToSeededData(): Promise<void> {
  const { clearAllDatabase } = await import('./db');
  await clearAllDatabase();
  localStorage.removeItem(STORAGE_KEY);
  for (const acc of SEED_DATA.accounts) {
    await saveAccount(acc);
  }
  for (const trd of SEED_DATA.trades) {
    await saveTrade(trd);
  }
}
